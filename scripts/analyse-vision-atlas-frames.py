"""Read immutable atlas alpha and export playback bounds; no image is changed.

The largest connected silhouette in each cell identifies the actor, excluding
stray pixels from a neighbouring pose. Playback uses these bounds to clip the
cell and place every pose's lowest contact point on the same 95% ground line.
"""
import json
from pathlib import Path
import numpy as np
from PIL import Image

root = Path(__file__).resolve().parent.parent
assets = root / 'src/assets/game-visions'
layouts = {}

def silhouette_bounds(alpha):
    # At 128px the connected-component scan is cheap and still separates the
    # narrow transparent gutters. Refine the winning box at source resolution.
    small = np.array(alpha.resize((128, 128), Image.Resampling.NEAREST)) > 160
    seen = np.zeros_like(small)
    largest = []
    for y, x in zip(*np.nonzero(small)):
        if seen[y, x]:
            continue
        stack = [(int(x), int(y))]
        component = []
        seen[y, x] = True
        while stack:
            px, py = stack.pop()
            component.append((px, py))
            for nx, ny in ((px-1,py),(px+1,py),(px,py-1),(px,py+1)):
                if 0 <= nx < 128 and 0 <= ny < 128 and small[ny,nx] and not seen[ny,nx]:
                    seen[ny,nx] = True
                    stack.append((nx,ny))
        if len(component) > len(largest):
            largest = component
    if not largest:
        return (0, 0, alpha.width, alpha.height)
    xs, ys = zip(*largest)
    scale_x, scale_y = alpha.width / 128, alpha.height / 128
    rough = (max(0, int(min(xs)*scale_x)-3), max(0, int(min(ys)*scale_y)-3),
             min(alpha.width, int((max(xs)+1)*scale_x)+3), min(alpha.height, int((max(ys)+1)*scale_y)+3))
    precise = alpha.crop(rough).point(lambda value: 255 if value > 160 else 0).getbbox()
    if precise is None:
        return rough
    return (rough[0]+precise[0],rough[1]+precise[1],rough[0]+precise[2],rough[1]+precise[3])

for folder, columns in [('characters',3),('walks',4)]:
    for path in sorted((assets/folder).glob('*.webp')):
        with Image.open(path) as sheet:
            alpha = sheet.getchannel('A')
            width, height = sheet.width//columns, sheet.height//2
            frames = []
            for row in range(2):
                for column in range(columns):
                    cell = alpha.crop((column*width,row*height,(column+1)*width,(row+1)*height))
                    left, top, right, bottom = silhouette_bounds(cell)
                    # Two pixels of antialias margin preserve the silhouette.
                    clip = [max(0,top-2)/height*100,max(0,width-right-2)/width*100,
                            max(0,height-bottom-2)/height*100,max(0,left-2)/width*100]
                    frames.append({'ground':round(95-bottom/height*100,3), 'clip':[round(v,3) for v in clip]})
            layouts[f'{folder}/{path.stem}'] = frames

target = root / 'src/games/visionAtlasLayout.ts'
target.write_text('// Generated by scripts/analyse-vision-atlas-frames.py from immutable atlas alpha.\n'
                  'export interface VisionAtlasFrame { ground: number; clip: number[]; }\n'
                  'export const VISION_ATLAS_LAYOUT: Record<string, VisionAtlasFrame[]> = '
                  +json.dumps(layouts, separators=(',',':'))+';\n', encoding='utf-8')
print(json.dumps({'atlases':len(layouts),'frames':sum(len(v) for v in layouts.values()),'output':str(target)}))
